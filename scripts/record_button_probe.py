"""Physical Record/Stop button tests using real audio capture, with no ASR or upload."""
import argparse
import json
import os
import subprocess
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
OUT = ROOT / "data/record-button-test"
sys.path.insert(0, str(ROOT))


def worker(baseline):
    import ctypes
    import time
    import threading
    import wave
    from unittest.mock import patch
    ctypes.windll.shcore.SetProcessDpiAwareness(2)
    import tkinter as tk
    import win32api
    import win32con
    import win32gui
    from speak.recording import Recorder
    from speak.providers import Result
    from speak.storage import DATA, Settings
    from speak.ui import App

    try:
        raw = json.loads((ROOT / "data/settings.json").read_text("utf-8"))
        microphone = raw.get("microphone")
        if microphone is not None and type(microphone) is not int:
            microphone = None
    except (OSError, ValueError):
        microphone = None
    DATA.mkdir(parents=True, exist_ok=True)
    Settings(mode="local", microphone=microphone, hotkey="Ctrl+Alt+F8", x=900, y=400).save()
    class AuditedRecorder(Recorder):
        active = 0
        maximum = 0
        starts = 0
        def start(self):
            super().start()
            self.counted = True
            type(self).starts += 1
            type(self).active += 1
            type(self).maximum = max(type(self).maximum, type(self).active)
        def stop(self):
            result = super().stop()
            if getattr(self, "counted", False):
                self.counted = False
                type(self).active -= 1
            return result
    with patch("speak.controller.Recorder", AuditedRecorder), patch("speak.providers.FreePriceGuard.check", return_value=None):
        root = tk.Tk()
        root.tk.call("tk", "scaling", 1.3333333333)
        app = App(root)
        app.controller.local.available = lambda: True
        # Audio is deliberately never decoded. Return no text and keep models unloaded.
        app.controller.local.segment = lambda *a: Result("", "probe", "no-asr", 0)
        errors, ticks, rows = [], [], []
        root.report_callback_exception = lambda kind, value, trace: errors.append(kind.__name__)
        cursor = win32api.GetCursorPos()
        def heartbeat():
            ticks.append(time.monotonic())
            if not app.shutting_down:
                root.after(10, heartbeat)
        heartbeat()
        def pump(seconds=.02):
            end = time.monotonic() + seconds
            while time.monotonic() < end:
                root.update()
                time.sleep(.001)
        def click():
            l, t, r, b = win32gui.GetWindowRect(app.hooks.hwnd)
            point = (l + 32, t + 35)
            hit = win32gui.WindowFromPoint(point)
            assert win32gui.GetAncestor(hit, win32con.GA_ROOT) == app.hooks.hwnd, "Test input intercepted"
            win32api.SetCursorPos(point)
            start = time.monotonic()
            win32api.mouse_event(win32con.MOUSEEVENTF_LEFTDOWN, 0, 0)
            win32api.mouse_event(win32con.MOUSEEVENTF_LEFTUP, 0, 0)
            pump(.005)
            return time.monotonic() - start
        def settle():
            deadline = time.monotonic() + 3
            while app.controller.state != "idle" and time.monotonic() < deadline:
                pump()
            assert app.controller.state == "idle", "Record/Stop task did not finish"
        def queued_clicks(count, gap):
            # Native input is generated by a separate thread while Tk may still
            # be inside PortAudio opening the microphone, like a real fast click.
            l, t, _, _ = win32gui.GetWindowRect(app.hooks.hwnd)
            point = (l + 32, t + 35)
            before = app.controller.task
            stamps, driver_errors = [], []
            finished = threading.Event()
            def drive():
                try:
                    win32api.SetCursorPos(point)
                    for index in range(count):
                        if index:
                            time.sleep(gap)
                        hit = win32gui.WindowFromPoint(point)
                        assert win32gui.GetAncestor(hit, win32con.GA_ROOT) == app.hooks.hwnd
                        assert win32api.GetCursorPos() == point, "Mouse moved during test"
                        stamps.append(time.monotonic())
                        win32api.mouse_event(win32con.MOUSEEVENTF_LEFTDOWN, 0, 0)
                        time.sleep(.003)
                        win32api.mouse_event(win32con.MOUSEEVENTF_LEFTUP, 0, 0)
                except Exception as exc:
                    driver_errors.append(type(exc).__name__)
                finally:
                    finished.set()
            thread = threading.Thread(target=drive, daemon=True)
            thread.start()
            deadline = time.monotonic() + 5
            while (not finished.is_set() or app.controller.task is before) and time.monotonic() < deadline:
                pump(.01)
            thread.join(.1)
            assert finished.is_set() and not driver_errors, driver_errors
            assert app.controller.task is not before
            pump(.05)
            return stamps
        try:
            pump(.15)
            delays = [0] if baseline else [0, .02, .05, .1, .2, .3, .5] * 2
            for delay in delays:
                pump(max(0, app.toggle_ready_at - time.monotonic()) + .03)
                start_duration = click()
                assert app.controller.state == "recording", "Record click not accepted"
                task = app.controller.task
                pump(delay)
                stop_duration = click()
                state_after_stop = app.controller.state
                if state_after_stop == "recording":
                    # Baseline cleanup uses the explicit preview Stop path.
                    app._stop_recording()
                settle()
                assert task.recorder.stream is None and not task.recorder.thread.is_alive()
                with wave.open(str(task.path), "rb") as audio:
                    frames = audio.getnframes()
                rows.append({"delay_ms": round(delay * 1000), "state_after_stop_click": state_after_stop,
                             "start_handler_ms": round(start_duration * 1000, 1),
                             "stop_handler_ms": round(stop_duration * 1000, 1), "frames": frames})
                if not baseline:
                    assert state_after_stop != "recording", rows[-1]
                    assert app.preview_window is None and AuditedRecorder.active == 0
            queued_rows = []
            burst_clicks = 0
            if not baseline:
                for gap in (0, .02, .05, .15):
                    pump(max(0, app.toggle_ready_at - time.monotonic()) + .03)
                    starts_before = AuditedRecorder.starts
                    stamps = queued_clicks(2, gap)
                    after_stop = app.controller.state
                    assert after_stop != "recording", "A stop queued during device open was lost"
                    settle()
                    assert AuditedRecorder.starts == starts_before + 1 and AuditedRecorder.active == 0
                    queued_rows.append({"requested_gap_ms": round(gap * 1000),
                                        "actual_gap_ms": round((stamps[1] - stamps[0]) * 1000, 1),
                                        "state_after_queued_stop": after_stop})
                pump(max(0, app.toggle_ready_at - time.monotonic()) + .03)
                queued_clicks(10, .02)
                if app.controller.state == "recording":
                    click()
                    assert app.controller.state != "recording"
                settle()
                assert AuditedRecorder.active == 0
                burst_clicks = 10
            report = {"status": "baseline" if baseline else "passed", "rounds": len(rows) + len(queued_rows), "samples": rows,
                      "queued_while_opening": queued_rows, "burst_clicks": burst_clicks,
                      "maximum_active_microphones": AuditedRecorder.maximum,
                      "active_after_test": AuditedRecorder.active, "ui_callback_errors": errors,
                      "local_model_started": bool(app.controller.local.process),
                      "scope": "Real selected microphone and physical Record/Stop clicks; no ASR, text insertion or cloud; WAVs deleted"}
            assert not errors and AuditedRecorder.maximum == 1 and AuditedRecorder.active == 0
            path = OUT / ("baseline.json" if baseline else "result.json")
            path.write_text(json.dumps(report, ensure_ascii=False, indent=2), "utf-8")
            print(json.dumps(report, ensure_ascii=False), flush=True)
        finally:
            app.close()
            win32api.SetCursorPos(cursor)


def main():
    parser = argparse.ArgumentParser()
    parser.add_argument("--worker", action="store_true", help=argparse.SUPPRESS)
    parser.add_argument("--baseline", action="store_true")
    args = parser.parse_args()
    OUT.mkdir(parents=True, exist_ok=True)
    if args.worker:
        worker(args.baseline)
        return
    profile = OUT / "profile"
    command = [sys.executable, "-X", "utf8", str(Path(__file__).resolve()), "--worker"]
    if args.baseline:
        command.append("--baseline")
    else:
        (OUT / "result.json").unlink(missing_ok=True)
    try:
        result = subprocess.run(command, cwd=ROOT, env=dict(os.environ, SPEAK_DATA_DIR=str(profile)),
                                capture_output=True, text=True, encoding="utf-8", timeout=45)
        print(result.stdout, end="")
        if result.returncode:
            print(result.stderr, end="", file=sys.stderr)
            raise SystemExit(result.returncode)
    finally:
        # Remove only WAVs created by this dedicated profile. Never touch user recordings.
        audio_dir = (profile / "audio").resolve()
        assert audio_dir.is_relative_to(OUT.resolve())
        for path in audio_dir.glob("*.wav"):
            path.unlink(missing_ok=True)


if __name__ == "__main__":
    main()
